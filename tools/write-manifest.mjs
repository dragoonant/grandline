#!/usr/bin/env node
// tools/write-manifest.mjs — regenerate art/manifest.js from what is actually on disk.
// It never invents an entry: if the file is not there, the card keeps its procedural placeholder.
import { readdir, writeFile, stat } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';
import { readFile } from 'node:fs/promises';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const DIR = join(ROOT, 'art', 'cards');
let files = [];
try { files = (await readdir(DIR)).filter((f) => f.endsWith('.webp')).sort(); } catch {}

const entries = [];
for (const f of files) {
  const s = await stat(join(DIR, f));
  if (s.size < 1000) { console.error('SKIP zero-length ' + f); continue; }
  entries.push([f.replace(/\.webp$/, ''), 'art/cards/' + f]);
}

let style = null;
try { style = JSON.parse(await readFile(join(ROOT, 'tools', 'art-prompts.json'), 'utf8')).style; } catch {}

await writeFile(join(ROOT, 'art', 'manifest.js'),
`// art/manifest.js — GENERATED by tools/write-manifest.mjs. Do not edit by hand.
//
// Declared on the page even while empty, and js/art.js THROWS if it is absent — lessons-5 §5.3,
// where 'RF.artManifest || {}' silently drew placeholder art over 59 paid renders.
(function (NS) {
  'use strict';
  NS.artManifest = {
${entries.map(([id, p]) => `    ${JSON.stringify(id)}: ${JSON.stringify(p)}`).join(',\n')}
  };
  NS.artMeta = {
    generated: ${JSON.stringify(new Date().toISOString().slice(0, 10))},
    count: ${entries.length},
    style: ${JSON.stringify(style)}
  };
}(window.OP = window.OP || {}));
`);
console.log(`${entries.length} renders in the manifest`);
